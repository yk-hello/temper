"""第三方许可证检查（D24、D98）：前端打进页面的 npm 包、后端编进程序的 Go 模块，许可证都要在允许的清单里。

    python tools/dev/licenses.py            只检查：有不允许的就列出来，退出码 1
    python tools/dev/licenses.py --write    检查通过后重写 THIRD_PARTY.md

只看会发出去的东西：npm 只看 package-lock.json 里不是 dev 的包（构建工具 vite、typescript 不进成品）；
Go 看 go list -m all 里真的被编进去的模块（读模块缓存里的 LICENSE 文件认许可证）。
"""

import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ALLOWED = {"MIT", "Apache-2.0", "ISC", "OFL-1.1", "BSD-3-Clause", "BSD-2-Clause", "0BSD"}

# LICENSE 文件里的特征句 → 许可证名。顺序有关：先认更具体的
PATTERNS = [
    ("Apache-2.0", r"Apache License\s+Version 2\.0"),
    ("ISC", r"ISC License|Permission to use, copy, modify, and(/or)? distribute this software for any"),
    ("MIT", r"MIT License|Permission is hereby granted, free of charge"),
    ("BSD-3-Clause", r"Redistribution and use in source and binary forms[\s\S]*Neither the name"),
    ("BSD-2-Clause", r"Redistribution and use in source and binary forms"),
    ("GPL/AGPL", r"GNU (Affero )?General Public License"),
]


# 装了但不进成品的包（查过构建出来的页面里没有它们的代码）：Perspective 的构建工具 pro_self_extracting_wasm
# 带进来的依赖（2026-11-14，D103 检查时查的：grep 构建产物找不到 leb128、buffer-pipe）。不算进第三方清单。
NOT_SHIPPED = {
    "leb128": "Perspective 的构建工具 pro_self_extracting_wasm 的依赖，MPL-2.0，不进页面",
    "buffer-pipe": "同上（leb128 的依赖），MPL-2.0，不进页面",
}


def npm_license_file(name):
    """package.json 没写许可证时，读包里的 LICENSE 文件认（比如 chroma-js 1.4.1 是 BSD）。"""
    d = os.path.join(ROOT, "web", "node_modules", *name.split("/"))
    for f in ("LICENSE", "LICENSE.md", "LICENSE.txt", "license"):
        fp = os.path.join(d, f)
        if os.path.exists(fp):
            text = open(fp, encoding="utf-8", errors="replace").read()
            return next((n for n, pat in PATTERNS if re.search(pat, text)), "?")
    return "?"


def pick(lic):
    """"(WTFPL OR MIT)" 这种可以任选其一的：选允许清单里的那个。"""
    alts = [x.strip() for x in lic.strip("()").split(" OR ")]
    return next((x for x in alts if x in ALLOWED), lic)


def npm():
    lock = json.load(open(os.path.join(ROOT, "web", "package-lock.json"), encoding="utf-8"))
    out = []
    for path, p in lock["packages"].items():
        if not path or p.get("dev") or p.get("devOptional"):
            continue
        name = path.split("node_modules/")[-1]
        if name in NOT_SHIPPED:
            continue
        lic = p.get("license") or "?"
        if isinstance(lic, dict):
            lic = lic.get("type", "?")
        if lic == "?":
            lic = npm_license_file(name)
        out.append(("npm", name, p.get("version", ""), pick(lic)))
    return out


def gomods():
    be = os.path.join(ROOT, "backend")
    cache = subprocess.check_output(["go", "env", "GOMODCACHE"], cwd=be, text=True).strip()
    mods = subprocess.check_output(["go", "list", "-deps", "-f", "{{if .Module}}{{.Module.Path}} {{.Module.Version}}{{end}}", "./..."], cwd=be, text=True)
    out = []
    for line in sorted(set(mods.split("\n"))):
        if not line.strip() or line.startswith("qs "):
            continue
        path, ver = line.split()
        # 模块缓存里大写字母写成 !小写
        esc = re.sub(r"[A-Z]", lambda m: "!" + m.group(0).lower(), path)
        d = os.path.join(cache, *esc.split("/")[:-1], esc.split("/")[-1] + "@" + ver)
        lic = "?"
        for f in ("LICENSE", "LICENSE.txt", "LICENSE.md", "COPYING", "license"):
            fp = os.path.join(d, f)
            if os.path.exists(fp):
                text = open(fp, encoding="utf-8", errors="replace").read()
                lic = next((name for name, pat in PATTERNS if re.search(pat, text)), "?")
                break
        out.append(("go", path, ver, lic))
    return out


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    rows = npm() + gomods()
    bad = [r for r in rows if r[3] not in ALLOWED]
    for r in bad:
        print(f"不允许或认不出：{r[0]} {r[1]} {r[2]} → {r[3]}")
    if bad:
        sys.exit(1)
    print(f"{len(rows)} 个第三方组件，许可证都在允许的清单里（{', '.join(sorted(ALLOWED))}）")
    if "--write" in sys.argv:
        lines = [
            "# Third-party components / 第三方组件",
            "",
            "Generated by `tools/dev/licenses.py --write`. Only components that ship in the built app are listed (build tools such as Vite and TypeScript are not).",
            "由 `tools/dev/licenses.py --write` 生成。只列会进成品的组件（Vite、TypeScript 这些构建工具不进成品）。",
            "",
            "| | Component | Version | License |",
            "| --- | --- | --- | --- |",
        ]
        for kind, name, ver, lic in sorted(rows):
            lines.append(f"| {kind} | {name} | {ver} | {lic} |")
        lines += ["", "Fonts (OFL-1.1) are bundled through the @fontsource packages; their license texts ship inside those packages.",
                  "字体（OFL-1.1）通过 @fontsource 包打进页面，许可证原文在这些包里。", ""]
        open(os.path.join(ROOT, "THIRD_PARTY.md"), "w", encoding="utf-8", newline="\n").write("\n".join(lines))
        print("已写 THIRD_PARTY.md")


if __name__ == "__main__":
    main()
